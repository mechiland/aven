#!/usr/bin/env python3
"""Generate original native KDE assets from Aven's focused token set.

No runtime dependency or style engine fork. Run from any working directory.
The optional Aurorae decoration must be checked in a real Plasma session before
being selected by the integrator. Its assets are not screenshot evidence.
"""
from __future__ import annotations

import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent
TOKENS = json.loads((ROOT / "tokens.json").read_text())


def put(path: str, content: str) -> None:
    target = ROOT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content.rstrip() + "\n")


def rgb(hex_color: str) -> str:
    return ",".join(str(int(hex_color[i:i + 2], 16)) for i in (1, 3, 5))


def colors() -> None:
    s, f, a = (TOKENS[k] for k in ("surface", "foreground", "accent"))
    groups = {
        "Button": (s["raised"], s["hover"], f["primary"], f["secondary"]),
        "Complementary": (s["complementary"], "#2E4940", "#F6F7F2", "#BCC9BF"),
        "Header": (s["chrome"], s["hover"], f["primary"], f["secondary"]),
        "Header][Inactive": (s["chromeInactive"], s["chrome"], f["secondary"], f["secondary"]),
        "Selection": (s["selection"], a["hover"], f["selected"], "#E9F0E9"),
        "Tooltip": (s["raised"], s["alternate"], f["primary"], f["secondary"]),
        "View": (s["content"], s["alternate"], f["primary"], f["secondary"]),
        "Window": (s["chrome"], s["alternate"], f["primary"], f["secondary"]),
    }
    lines = ["# Generated by visual/generate_assets.py from visual/tokens.json.",
             "[ColorEffects:Disabled]", "Color=101,112,106", "ColorAmount=0", "ColorEffect=0",
             "ContrastAmount=0.55", "ContrastEffect=1", "IntensityAmount=0", "IntensityEffect=0", "",
             "[ColorEffects:Inactive]", "ChangeSelectionColor=true", "Color=220,232,224",
             "ColorAmount=0.1", "ColorEffect=2", "ContrastAmount=0.1", "ContrastEffect=2",
             "Enable=false", "IntensityAmount=0", "IntensityEffect=0", ""]
    for name, (bg, alt, fg, dim) in groups.items():
        selected = name in {"Selection", "Complementary"}
        entries = {"BackgroundNormal": bg, "BackgroundAlternate": alt,
                   "DecorationFocus": a["primary"], "DecorationHover": a["hover"],
                   "ForegroundNormal": fg, "ForegroundInactive": dim,
                   "ForegroundActive": fg if selected else a["primary"],
                   "ForegroundLink": "#C7E8DF" if selected else a["pressed"],
                   "ForegroundVisited": "#E2D1EA" if selected else "#775681",
                   "ForegroundNegative": "#FFD6CB" if selected else f["negative"],
                   "ForegroundNeutral": "#F3DFB1" if selected else f["neutral"],
                   "ForegroundPositive": "#C4E8CA" if selected else f["positive"]}
        lines.append(f"[Colors:{name}]")
        lines.extend(f"{key}={rgb(value)}" for key, value in entries.items())
        lines.append("")
    lines += ["[General]", "ColorScheme=AvenMist", "Name=Aven Mist", "Name[zh_CN]=Aven 薄雾",
              "Name[zh_TW]=Aven 薄霧", "shadeSortColumn=false", "", "[KDE]", "contrast=2", "", "[WM]"]
    for key, value in {"activeBackground": s["chrome"], "activeBlend": s["chrome"],
                       "activeForeground": f["primary"], "inactiveBackground": s["chromeInactive"],
                       "inactiveBlend": s["chromeInactive"], "inactiveForeground": f["secondary"]}.items():
        lines.append(f"{key}={rgb(value)}")
    put("color-schemes/AvenMist.colors", "\n".join(lines))


