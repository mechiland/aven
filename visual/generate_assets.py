    # Generic directory rows request the MIME icon, while named XDG folders
    # request places icons. Cover both, otherwise small generic folders inherit
    # Breeze's outlined inode-directory beside Aven's filled semantic folders.
    folder = (ROOT / "icons/Aven/scalable/places/folder.svg").read_text()
